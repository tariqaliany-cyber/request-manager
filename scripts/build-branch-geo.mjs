// Builds src/branchGeo.js from the two caches made by
// resolve-branch-coords.mjs and reverse-geocode-districts.mjs, plus the
// geoBoundaries SAU ADM1 GeoJSON (to take each pin's region from where it
// actually is, not from its city name).
//   node scripts/build-branch-geo.mjs <coords.json> <districts.json> <sau-adm1.geojson>
import fs from 'fs';

const [coordsFile, districtsFile, geoFile] = process.argv.slice(2);
const coords    = JSON.parse(fs.readFileSync(coordsFile, 'utf8'));
const districts = JSON.parse(fs.readFileSync(districtsFile, 'utf8'));
const geo       = JSON.parse(fs.readFileSync(geoFile, 'utf8'));

const ISO_TO_ID = { 'SA-01': 'riyadh', 'SA-02': 'makkah', 'SA-03': 'madinah', 'SA-04': 'eastern', 'SA-05': 'qassim', 'SA-06': 'hail', 'SA-07': 'tabuk', 'SA-08': 'northern', 'SA-09': 'jazan', 'SA-10': 'najran', 'SA-11': 'baha', 'SA-12': 'jawf', 'SA-14': 'asir' };

const inRing = ([x, y], ring) => {
  let inside = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i], [xj, yj] = ring[j];
    if ((yi > y) !== (yj > y) && x < (xj - xi) * (y - yi) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
};
function regionOf(pt) {
  for (const f of geo.features) {
    const polys = f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates;
    if (polys.some(p => inRing(pt, p[0]) && !p.slice(1).some(h => inRing(pt, h)))) return ISO_TO_ID[f.properties.shapeISO];
  }
  return null;   // on the coast / just outside the simplified outline
}

// Drop generic prefixes so "حي العليا" and "العليا" group together.
const cleanDistrict = (d) => (d || '').replace(/^(حي|حى)\s+/, '').trim() || null;

const out = {};
for (const [num, pt] of Object.entries(coords)) {
  if (!pt) continue;
  const d = districts[num] || {};
  out[num] = [+pt[0].toFixed(5), +pt[1].toFixed(5), regionOf(pt), cleanDistrict(d.district)];
}

const src = `// Generated by scripts/build-branch-geo.mjs: each branch's map pin (from its
// Google Maps link in location.xlsx), the region the pin falls in, and its
// district (حي) from OpenStreetMap Nominatim reverse geocoding (© OSM
// contributors, ODbL). Regenerate rather than editing by hand.
// branch number → [lon, lat, regionId | null, district | null]
export const BRANCH_GEO = ${JSON.stringify(out)};
`;
fs.writeFileSync('src/branchGeo.js', src);
const n = Object.values(out);
console.log('branches', n.length, 'no region', n.filter(v => !v[2]).length, 'no district', n.filter(v => !v[3]).length);
